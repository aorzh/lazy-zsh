Quick tips
----------
  type a few letters      grey suggestion from history: Right arrow or End accepts it
  prefix + Up arrow       cycles only through commands starting with that prefix
  Ctrl-R                  fuzzy search in the whole history (Ctrl-T files, Alt-C dirs)
  Esc Esc                 put sudo in front of the current or last command
  x file.tar.gz           extract any archive
  " cmd"                  leading space = not saved to history (tokens, passwords)
  alias | grep git        git shortcuts from the git plugin: gst, gco, gp, glog, ...
  omz update              update oh-my-zsh (re-run install.sh to update the rest)
  ~/.zshrc.local          your own PATH, functions, exports; never overwritten
  ZSH_THEME in ~/.zshrc   change the prompt theme (ls ~/.oh-my-zsh/themes)
  ./rollback.sh           undo everything and go back to bash

Open a new terminal tab, or run: exec zsh -l
TIPS
